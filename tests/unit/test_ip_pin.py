def _make_runner_with_cache(pins=None, entries=None):
    from blockchecks.engine.async_runner import AsyncTestRunner

    cache = DnsRunCache()
    for domain, ips in (entries or {}).items():
        cache.set(domain, ips)
    cache.set_pins(pins or {})
    runner = AsyncTestRunner(pool_size=1, dns_cache=cache, pinned_path="/tmp/pins_test.conf")
    return runner, cache


@pytest.mark.asyncio(loop_scope="package")
async def test_auto_pin_writes_only_when_changed(tmp_path):
    """Save happens only when a pin IP actually changes (git stays clean)."""

    path = str(tmp_path / "hosts")
    with open(path, "w", encoding="utf-8") as f:
        f.write("162.159.135.232\tdiscord.com\n")  # already-working pin

    runner, cache = _make_runner_with_cache(
        pins={"discord.com": "162.159.135.232"},
        entries={"discord.com": ["162.159.136.232", "162.159.135.232"]},
    )
    runner.pinned_path = path

    # pinned IP still works -> file content unchanged -> no rewrite
    with patch.object(runner, "_probe_pin_ip", new_callable=AsyncMock) as probe:
        probe.return_value = True
        await runner._auto_pin_ips()
    with open(path, encoding="utf-8") as f:
        content_before = f.read()
    mtime_before = os.path.getmtime(path)
    time.sleep(0.05)
    with patch.object(runner, "_probe_pin_ip", new_callable=AsyncMock) as probe:
        probe.return_value = True
        await runner._auto_pin_ips()
    with open(path, encoding="utf-8") as f:
        content_after = f.read()
    assert content_after == content_before
    assert os.path.getmtime(path) == mtime_before

    # pinned IP fails, fallback works -> file updated
    async def _probe(domain, ip):
        return ip == "162.159.136.232"

    with patch.object(runner, "_probe_pin_ip", new_callable=AsyncMock) as probe:
        probe.side_effect = _probe
        await runner._auto_pin_ips()
    with open(path, encoding="utf-8") as f:
        updated = f.read()
    assert "162.159.136.232\tdiscord.com" in updated
    assert "162.159.135.232" not in updated.split("\t")[0]
